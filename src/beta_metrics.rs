fn measure_throughput(
    harness: &mut Harness,
    fixture: &Path,
    session_index: usize,
    mode: &str,
) -> Result<f64> {
    let marker = format!(
        "BLUEBERRY_BETA_OUTPUT_DONE_{mode}_{session_index}_{}",
        uuid::Uuid::new_v4()
    );
    let command = format!(
        "Get-Content -Raw -LiteralPath '{}'; Write-Output '{}'",
        powershell_quote(fixture),
        marker
    );
    let started = Instant::now();
    harness.send(command.as_bytes())?;
    harness.send(b"\r")?;
    wait_for_line(harness, &marker, WAIT_TIMEOUT)?;
    let elapsed = started.elapsed().as_secs_f64().max(f64::EPSILON);
    Ok(OUTPUT_BYTES as f64 / elapsed)
}

fn measure_pwsh_baseline(
    shell: &Path,
    cwd: &Path,
    environment: &BTreeMap<String, String>,
    fixtures: &Fixtures,
) -> Result<Value> {
    let mut baseline_environment = environment.clone();
    baseline_environment.remove("BLUEBERRY_ACTIVE");
    baseline_environment.remove("BLUEBERRY_TRACE");
    // BLUEBERRY_NO_HISTORY is consumed by the adapter and has no meaning to
    // a bare PowerShell process. Explicitly configure PSReadLine after the
    // normal profile has loaded, so this throughput control cannot write the
    // user's history. CI may select a pinned PSReadLine module; load that
    // same module before applying the option to keep the control comparable.
    let mut history_setup = String::new();
    if let Some(module) =
        env::var_os("BLUEBERRY_TEST_PSREADLINE_MODULE").filter(|module| !module.is_empty())
    {
        let module = PathBuf::from(module);
        history_setup.push_str("Import-Module '");
        history_setup.push_str(&powershell_quote(&module));
        history_setup.push_str("' -Force; ");
    }
    history_setup
        .push_str("Import-Module PSReadLine; Set-PSReadLineOption -HistorySaveStyle SaveNothing;");
    let args = vec![
        "-NoLogo".to_owned(),
        "-NoExit".to_owned(),
        "-Command".to_owned(),
        history_setup,
    ];
    let mut harness = Harness::start(
        shell,
        &args,
        cwd,
        &baseline_environment,
        uuid::Uuid::new_v4().to_string(),
    )?;
    wait_for_prompt(&mut harness, WAIT_TIMEOUT)?;
    let mut input_echo = Vec::with_capacity(10);
    for index in 0..10 {
        let line = format!("SS_ECHO_CONTROL_{index}");
        let started = Instant::now();
        harness.send(line.as_bytes())?;
        let deadline = started + WAIT_TIMEOUT;
        loop {
            if has_input_echo(&harness.viewport_contents(), &line) {
                input_echo.push(milliseconds(started.elapsed()));
                break;
            }
            if Instant::now() >= deadline {
                bail!(
                    "独立 PowerShell 输入回显对照超时，样本 {index}；screen:\n{}",
                    harness.viewport_contents()
                );
            }
            pump_brief(&mut harness, deadline);
        }
        reset_line(&mut harness, &line)?;
    }
    let marker = format!("BLUEBERRY_BETA_BASELINE_DONE_{}", uuid::Uuid::new_v4());
    let command = format!(
        "Get-Content -Raw -LiteralPath '{}'; Write-Output '{}'",
        powershell_quote(&fixtures.throughput),
        marker
    );
    let started = Instant::now();
    harness.send(command.as_bytes())?;
    harness.send(b"\r")?;
    wait_for_line(&mut harness, &marker, WAIT_TIMEOUT)?;
    let elapsed = started.elapsed().as_secs_f64().max(f64::EPSILON);
    let throughput = OUTPUT_BYTES as f64 / elapsed;
    harness.finish(WAIT_TIMEOUT)?;
    Ok(json!({
        "throughput": f64_stats(&[throughput], "bytes_per_second"),
        "input_echo_control": f64_stats(&input_echo, "ms"),
        "input_echo_control_note": "10 个编辑后清空、不执行的输入样本，仅诊断；不替代正式宿主热态验收",
        "profile_mode": "preserved",
        "shell": shell,
        "method": "同一 shell、cwd 和固定文本夹具；没有 --no-profile，也没有 Blueberry host",
    }))
}

fn powershell_quote(path: &Path) -> String {
    path.to_string_lossy().replace('\'', "''")
}

fn wait_for_line(harness: &mut Harness, text: &str, timeout: Duration) -> Result<()> {
    let deadline = Instant::now() + timeout;
    loop {
        if harness.contents().lines().any(|line| line.trim() == text) {
            return Ok(());
        }
        if Instant::now() >= deadline {
            bail!(
                "等待输出标记 `{text}` 超时；screen:\n{}",
                harness.viewport_contents()
            );
        }
        // Harness::pump reports a timeout when no PTY bytes arrived in the
        // short interval.  Keep polling until the bounded overall deadline;
        // an EOF is reported with the final screen if the deadline expires.
        pump_brief(harness, deadline);
    }
}

fn adapter_paths(data_dir: &Path) -> BTreeSet<PathBuf> {
    fs::read_dir(data_dir)
        .into_iter()
        .flatten()
        .filter_map(|entry| {
            let path = entry.ok()?.path().join("adapter.json");
            path.is_file().then_some(path)
        })
        .collect()
}

fn wait_for_transport(
    data_dir: &Path,
    requested: &str,
    previous_adapters: &BTreeSet<PathBuf>,
) -> Result<String> {
    let deadline = Instant::now() + Duration::from_secs(2);
    loop {
        if let Ok(entries) = fs::read_dir(data_dir) {
            for entry in entries.flatten() {
                let path = entry.path().join("adapter.json");
                if previous_adapters.contains(&path) {
                    continue;
                }
                let Ok(bytes) = fs::read(&path) else {
                    continue;
                };
                let Ok(value) = serde_json::from_slice::<Value>(&bytes) else {
                    continue;
                };
                if let Some(actual) = value.get("transport").and_then(Value::as_str) {
                    ensure!(
                        matches!(actual, "osc" | "pipe"),
                        "适配器报告未知 transport={actual}（请求 {requested}）"
                    );
                    return Ok(actual.to_owned());
                }
            }
        }
        if Instant::now() >= deadline {
            bail!(
                "等待 adapter.json transport 超时（请求 {requested}）；data_dir={} ",
                data_dir.display()
            );
        }
        thread::sleep(Duration::from_millis(20));
    }
}

fn sample_memory(values: &mut Vec<u64>, harness: &Harness) {
    if let Some(value) = harness.process_id().and_then(working_set_bytes) {
        values.push(value);
    }
}

fn idle_cpu_percent(harness: &Harness) -> Option<f64> {
    let process_id = harness.process_id()?;
    let before = process_cpu_100ns(process_id)?;
    let started = Instant::now();
    thread::sleep(IDLE_CPU_SAMPLE);
    let after = process_cpu_100ns(process_id)?;
    let elapsed_100ns = started.elapsed().as_secs_f64() * 10_000_000.0;
    if elapsed_100ns <= 0.0 {
        return None;
    }
    Some((after.saturating_sub(before) as f64 / elapsed_100ns) * 100.0)
}

#[cfg(windows)]
fn working_set_bytes(process_id: u32) -> Option<u64> {
    use std::mem::size_of;
    use windows_sys::Win32::{
        Foundation::CloseHandle,
        System::{
            ProcessStatus::{K32GetProcessMemoryInfo, PROCESS_MEMORY_COUNTERS},
            Threading::{OpenProcess, PROCESS_QUERY_LIMITED_INFORMATION, PROCESS_VM_READ},
        },
    };
    // SAFETY: the PID comes from the live Harness child, and the handle is
    // closed on every successful OpenProcess path below.
    let handle = unsafe {
        OpenProcess(
            PROCESS_QUERY_LIMITED_INFORMATION | PROCESS_VM_READ,
            0,
            process_id,
        )
    };
    if handle.is_null() {
        return None;
    }
    let mut counters = PROCESS_MEMORY_COUNTERS {
        cb: size_of::<PROCESS_MEMORY_COUNTERS>() as u32,
        ..Default::default()
    };
    // SAFETY: `counters` is a writable value with its documented size.
    let ok = unsafe { K32GetProcessMemoryInfo(handle, &mut counters, counters.cb) != 0 };
    // SAFETY: this handle was returned by OpenProcess and is closed once.
    unsafe { CloseHandle(handle) };
    ok.then_some(counters.WorkingSetSize as u64)
}

#[cfg(not(windows))]
fn working_set_bytes(_process_id: u32) -> Option<u64> {
    None
}

#[cfg(windows)]
fn process_cpu_100ns(process_id: u32) -> Option<u64> {
    use windows_sys::Win32::{
        Foundation::{CloseHandle, FILETIME},
        System::Threading::{GetProcessTimes, OpenProcess, PROCESS_QUERY_LIMITED_INFORMATION},
    };
    // SAFETY: the PID is supplied by the live Harness process.
    let handle = unsafe { OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, 0, process_id) };
    if handle.is_null() {
        return None;
    }
    let mut creation = FILETIME::default();
    let mut exit = FILETIME::default();
    let mut kernel = FILETIME::default();
    let mut user = FILETIME::default();
    // SAFETY: all FILETIME pointers refer to writable local values.
    let ok =
        unsafe { GetProcessTimes(handle, &mut creation, &mut exit, &mut kernel, &mut user) != 0 };
    // SAFETY: this handle was returned by OpenProcess and is closed once.
    unsafe { CloseHandle(handle) };
    ok.then_some(filetime_100ns(kernel).saturating_add(filetime_100ns(user)))
}

#[cfg(not(windows))]
fn process_cpu_100ns(_process_id: u32) -> Option<u64> {
    None
}

#[cfg(windows)]
fn filetime_100ns(value: windows_sys::Win32::Foundation::FILETIME) -> u64 {
    (u64::from(value.dwHighDateTime) << 32) | u64::from(value.dwLowDateTime)
}

fn milliseconds(duration: Duration) -> f64 {
    duration.as_secs_f64() * 1_000.0
}

fn p95_index(length: usize) -> usize {
    // Nearest rank: ceil(0.95 * N), represented as a zero-based index.
    ((length * 95).saturating_add(99) / 100)
        .saturating_sub(1)
        .min(length.saturating_sub(1))
}

fn f64_stats(values: &[f64], unit: &str) -> Value {
    if values.is_empty() {
        return json!({
            "available": false,
            "samples": [],
            "missing": true,
            "unit": unit,
        });
    }
    let mut sorted = values.to_vec();
    sorted.sort_by(f64::total_cmp);
    json!({
        "available": true,
        "samples": values,
        "median": (sorted[(sorted.len() - 1) / 2] + sorted[sorted.len() / 2]) / 2.0,
        "p95": sorted[p95_index(sorted.len())],
        "unit": unit,
    })
}

fn u64_stats(values: &[u64], unit: &str) -> Value {
    if values.is_empty() {
        return json!({
            "available": false,
            "samples": [],
            "missing": true,
            "unit": unit,
        });
    }
    let mut sorted = values.to_vec();
    sorted.sort_unstable();
    let low = sorted[(sorted.len() - 1) / 2] as f64;
    let high = sorted[sorted.len() / 2] as f64;
    json!({
        "available": true,
        "samples": values,
        "median": (low + high) / 2.0,
        "p95": sorted[p95_index(sorted.len())],
        "unit": unit,
    })
}

fn verify_complete_cache(data_dir: &Path) -> Result<bool> {
    let path = data_dir.join("commands.json");
    let bytes =
        fs::read(&path).with_context(|| format!("缺少性能夹具命令缓存 {}", path.display()))?;
    let value: Value = serde_json::from_slice(&bytes)
        .with_context(|| format!("命令缓存不是 JSON: {}", path.display()))?;
    ensure!(
        value.get("complete").and_then(Value::as_bool) == Some(true),
        "命令缓存 {} 未标记 complete=true",
        path.display()
    );
    Ok(true)
}
