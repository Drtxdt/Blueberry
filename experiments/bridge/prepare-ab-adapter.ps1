function Publish-ShellsenseBridgeProof {
    [CmdletBinding()]
    param()

    # This is a one-time, temp-directory marker for the A/B runner. It is
    # intentionally outside the protocol and is never written per query.
    if ($script:SHELLSENSE_BRIDGE_PROOF_PUBLISHED) {
        return
    }
    $script:SHELLSENSE_BRIDGE_PROOF_PUBLISHED = $true
    $temporaryPath = [string]$script:SHELLSENSE_BRIDGE_PROOF_PATH + '.' + [string]$PID + '.tmp'
    try {
        $payload = [ordered]@{
            schema       = 1
            mode         = 'bridge'
            bound        = $true
            process_id   = [int]$PID
            runtime      = [string]$PSVersionTable.PSVersion
            assembly     = [string]$script:SHELLSENSE_BRIDGE_DLL_PATH
            timestamp_utc = [DateTime]::UtcNow.ToString('O')
            surface      = @('GetKeyHandlers', 'GetBufferState', 'Replace', 'SetKeyHandler', 'Serialize')
        }
        $json = [ShellSense.Bridge.PsReadLineBridge]::Serialize($payload)
        $encoding = [Text.UTF8Encoding]::new($false)
        [IO.File]::WriteAllText($temporaryPath, $json + [Environment]::NewLine, $encoding)
        try {
            [IO.File]::Move($temporaryPath, [string]$script:SHELLSENSE_BRIDGE_PROOF_PATH)
        } catch {
            # Another adapter child may have published the shared marker first.
            if (-not [IO.File]::Exists([string]$script:SHELLSENSE_BRIDGE_PROOF_PATH)) {
                throw
            }
        }
    } catch {
        try { [IO.File]::Delete($temporaryPath) } catch { }
    }
}

function Publish-ShellsenseBridgeFallback {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [string]$Operation,

        [AllowEmptyString()]
        [string]$ErrorMessage = ''
    )

    # An invocation failure is exceptional and is recorded once for the
    # runner. A successful bridge path never writes this file, so normal
    # performance samples have no per-query filesystem write.
    if ($script:SHELLSENSE_BRIDGE_FALLBACK_PUBLISHED) {
        return
    }
    $script:SHELLSENSE_BRIDGE_FALLBACK_PUBLISHED = $true
    $temporaryPath = [string]$script:SHELLSENSE_BRIDGE_FALLBACK_PATH + '.' + [string]$PID + '.tmp'
    try {
        $payload = [ordered]@{
            schema       = 1
            mode         = 'fallback'
            bridge_call  = $false
            operation    = $Operation
            error        = $ErrorMessage
            process_id   = [int]$PID
            timestamp_utc = [DateTime]::UtcNow.ToString('O')
        }
        $json = [ShellSense.Bridge.PsReadLineBridge]::Serialize($payload)
        $encoding = [Text.UTF8Encoding]::new($false)
        [IO.File]::WriteAllText($temporaryPath, $json + [Environment]::NewLine, $encoding)
        try {
            [IO.File]::Move($temporaryPath, [string]$script:SHELLSENSE_BRIDGE_FALLBACK_PATH)
        } catch {
            if (-not [IO.File]::Exists([string]$script:SHELLSENSE_BRIDGE_FALLBACK_PATH)) {
                throw
            }
        }
    } catch {
        try { [IO.File]::Delete($temporaryPath) } catch { }
    }
}

function Test-ShellsenseBridge {
    [CmdletBinding()]
    param()

    if ($script:SHELLSENSE_BRIDGE_BOUND) {
        return $true
    }
    try {
        if ($null -eq $script:SHELLSENSE_BRIDGE_ASSEMBLY) {
            if (-not [IO.File]::Exists([string]$script:SHELLSENSE_BRIDGE_DLL_PATH)) {
                return $false
            }
            $script:SHELLSENSE_BRIDGE_ASSEMBLY = [Reflection.Assembly]::LoadFrom(
                [string]$script:SHELLSENSE_BRIDGE_DLL_PATH)
        }
        $bindError = ''
        $script:SHELLSENSE_BRIDGE_BOUND = [ShellSense.Bridge.PsReadLineBridge]::TryBind(
            [ref]$bindError)
        if ($script:SHELLSENSE_BRIDGE_BOUND) {
            Publish-ShellsenseBridgeProof
        }
    } catch {
        $script:SHELLSENSE_BRIDGE_BOUND = $false
    }
    return [bool]$script:SHELLSENSE_BRIDGE_BOUND
}

function Invoke-ShellsenseBridgeGetBufferState {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [ref]$Line,

        [Parameter(Mandatory = $true)]
        [ref]$Cursor
    )

    if (Test-ShellsenseBridge) {
        $state = $null
        $bridgeError = ''
        if ([ShellSense.Bridge.PsReadLineBridge]::TryGetBufferState(
                [ref]$state, [ref]$bridgeError)) {
            $Line.Value = [string]$state.Line
            $Cursor.Value = [int]$state.Cursor
            return
        }
        Publish-ShellsenseBridgeFallback -Operation 'GetBufferState' -ErrorMessage $bridgeError
    }
    [Microsoft.PowerShell.PSConsoleReadLine]::GetBufferState($Line, $Cursor)
}

function Invoke-ShellsenseBridgeReplace {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [int]$Start,

        [Parameter(Mandatory = $true)]
        [int]$Length,

        [Parameter(Mandatory = $true)]
        [AllowEmptyString()]
        [string]$Replacement
    )

    if (Test-ShellsenseBridge) {
        $bridgeError = ''
        if ([ShellSense.Bridge.PsReadLineBridge]::TryReplace(
                $Start, $Length, $Replacement, [ref]$bridgeError)) {
            return
        }
        Publish-ShellsenseBridgeFallback -Operation 'Replace' -ErrorMessage $bridgeError
    }
    [Microsoft.PowerShell.PSConsoleReadLine]::Replace(
        $Start, $Length, $Replacement, $null, $null)
}

function Convert-ShellsenseBridgeHandler {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [object]$Handler
    )

    return [pscustomobject]@{
        Key         = [string]$Handler.Key
        Function    = [string]$Handler.Function
        Description = [string]$Handler.Description
        Group       = [string]$Handler.Group
    }
}

function Convert-ShellsenseBridgeHandlerSnapshot {
    [CmdletBinding()]
    param()

    if (-not (Test-ShellsenseBridge)) {
        return $null
    }
    try {
        $snapshot = [ShellSense.Bridge.PsReadLineBridge]::GetKeyHandlerSnapshot()
        if (-not $snapshot.Available) {
            Publish-ShellsenseBridgeFallback -Operation 'GetKeyHandlers' -ErrorMessage ([string]$snapshot.Error)
            return $null
        }
        $handlers = [System.Collections.Generic.List[object]]::new()
        $byChord = [System.Collections.Generic.Dictionary[string, object]]::new(
            [StringComparer]::OrdinalIgnoreCase)
        foreach ($handler in $snapshot.Handlers) {
            [void]$handlers.Add((Convert-ShellsenseBridgeHandler -Handler $handler))
        }
        foreach ($pair in $snapshot.ByChord.GetEnumerator()) {
            $chordHandlers = [System.Collections.Generic.List[object]]::new()
            foreach ($handler in $pair.Value) {
                [void]$chordHandlers.Add((Convert-ShellsenseBridgeHandler -Handler $handler))
            }
            $byChord[$pair.Key] = $chordHandlers
        }
        return [pscustomobject]@{
            available = $true
            handlers  = [object[]]$handlers.ToArray()
            by_chord  = $byChord
        }
    } catch {
        Publish-ShellsenseBridgeFallback -Operation 'GetKeyHandlers' -ErrorMessage $_.Exception.Message
        return $null
    }
}

'@
    $bridgePrologue = $bridgePrologue.Replace('__SHELLSENSE_BRIDGE_DLL_PATH__', $bridgeLiteral)
    $bridgePrologue = $bridgePrologue.Replace('__SHELLSENSE_BRIDGE_PROOF_PATH__', $proofLiteral)

    $bufferCall = '[Microsoft.PowerShell.PSConsoleReadLine]::GetBufferState([ref]$line, [ref]$cursor)'
    $bufferReplacement = 'Invoke-ShellsenseBridgeGetBufferState -Line ([ref]$line) -Cursor ([ref]$cursor)'
    $bufferCallCount = ([regex]::Matches($adapterSource, [regex]::Escape($bufferCall))).Count
    if ($bufferCallCount -ne 4) {
