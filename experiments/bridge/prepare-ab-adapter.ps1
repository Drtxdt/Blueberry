        }

'@
    $adapterSource = $adapterSource.Replace($serializationAnchor, $serializationBranch + $serializationAnchor)
    [void]$transformations.Add('Serialize: cached bridge options')

    $snapshotAnchor = @'
function Get-ShellsenseKeyHandlerSnapshot {
    [CmdletBinding()]
    param()
'@
    if (([regex]::Matches($adapterSource, [regex]::Escape($snapshotAnchor))).Count -ne 1) {
        throw 'Adapter shape changed: key snapshot function was not found'
    }
    $snapshotBranch = @'
    $bridgeSnapshot = Convert-ShellsenseBridgeHandlerSnapshot
    if ($null -ne $bridgeSnapshot) {
        return $bridgeSnapshot
    }

'@
    $adapterSource = $adapterSource.Replace($snapshotAnchor, $snapshotAnchor + $snapshotBranch)
    [void]$transformations.Add('GetKeyHandlers: immutable bridge snapshot')

    $registerAnchor = @'
    if (-not $SkipCollisionCheck -and @(Get-ShellsenseKeyBinding -Chord $Chord).Count -gt 0) {
'@
    if (([regex]::Matches($adapterSource, [regex]::Escape($registerAnchor))).Count -ne 1) {
        throw 'Adapter shape changed: key registration anchor was not found'
    }
    $registerBranch = @'
    if (Test-ShellsenseBridge) {
        $bridgeError = ''
        if ([ShellSense.Bridge.PsReadLineBridge]::TrySetKeyHandler(
                $Chord,
                $ScriptBlock,
                ('Shellsense ' + $Name),
                ('Report shellsense ' + $Name + ' state.'),
                [ref]$bridgeError)) {
            return $true
        }
        Publish-ShellsenseBridgeFallback -Operation 'SetKeyHandler' -ErrorMessage $bridgeError
    }

'@
    $adapterSource = $adapterSource.Replace($registerAnchor, $registerBranch + $registerAnchor)
    [void]$transformations.Add('SetKeyHandler: public registration wrapper')

    $adapterSource = $bridgePrologue + $adapterSource
}

