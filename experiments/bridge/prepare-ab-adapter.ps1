    $serializationAnchor = '        # The explicit object/type/options overload keeps PowerShell from'
    if (([regex]::Matches($adapterSource, [regex]::Escape($serializationAnchor))).Count -ne 1) {
        throw 'Adapter shape changed: JSON serialization anchor was not found'
    }
    $serializationBranch = @'
